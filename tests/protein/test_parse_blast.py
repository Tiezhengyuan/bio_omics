'''
example: pytest -s tests/protein/test_parse_blast.py

The fixture tests/data/blast/vregion_blastp.xml was generated by:
    makeblastdb -parse_seqids -in vregion_db.faa -dbtype prot -out vregion_db
    blastp -query vregion_query.faa -db vregion_db \
        -outfmt 5 -evalue 1e-5 -out vregion_blastp.xml

vregion_query.faa holds two queries:
    query_hit: IGHV1-2 like, one mismatch at the last residue vs IGHV1-2*02
    query_none: ubiquitin, no hit at e-value 1e-5
'''
from ..helper import *

from src.bioomics import ParseBlastXml

ALN_FILE = os.path.join(DATA_DIR, 'blast', 'vregion_blastp.xml')

@ddt
class TestParseBlast(TestCase):

    def setUp(self):
        self.p = ParseBlastXml(ALN_FILE)

    def test_record_iter(self):
        records = list(self.p.record_iter())
        assert len(records) == 2
        assert [r.query for r in records] == ['query_hit', 'query_none']
        assert [r.query_length for r in records] == [98, 76]

    def test_alignments(self):
        records = list(self.p.record_iter())
        aln = self.p.alignments(records[0])
        assert len(aln) == 2
        best = aln[0]
        assert best['hit_id'] == 'IGHV1-2*02|Homo_sapiens'
        assert best['hit_desc'] == 'No definition line'
        assert best['identities'] == 97
        assert best['align_len'] == 97
        assert best['identity'] == 1.0
        assert len(best['query_seq']) == 97
        assert len(best['match_seq']) == 97
        assert len(best['sbjct_seq']) == 97
        assert best['query_start'] == 1
        assert best['sbjct_end'] == 97
        # the query without hit holds no alignment
        assert self.p.alignments(records[1]) == []

    def test_best_hits(self):
        result = self.p.best_hits()
        assert len(result) == 2
        hit = [r for r in result if r['query'] == 'query_hit'][0]
        assert hit['hit_id'] == 'IGHV1-2*02|Homo_sapiens'
        assert hit['query_len'] == 98
        assert hit['evalue'] < 1e-50
        assert hit['bit_score'] > 200
        # query without hit only holds query info
        none = [r for r in result if r['query'] == 'query_none'][0]
        assert none['query_len'] == 76
        assert 'hit_id' not in none

    def test_hits(self):
        result = self.p.hits()
        assert len(result) == 2
        assert [r['query'] for r in result] == ['query_hit', 'query_hit']
        # blast ranks hits by e-value
        assert result[0]['evalue'] < result[1]['evalue']
        for hit in result:
            assert 0 < hit['identity'] <= 1
            assert len(hit['query_seq']) == len(hit['sbjct_seq'])

    @data(
        ['IGHV1-2*02|Homo_sapiens', {'allele_name': 'IGHV1-2*02',
            'specie': 'Homo_sapiens', 'gene_name': 'IGHV1-2',
            'gene_family': 'IGHV1', 'isotype': 'IG', 'chain_type': 'H'}],
        ['TRBV6-1*01', {'allele_name': 'TRBV6-1*01', 'gene_name': 'TRBV6-1',
            'gene_family': 'TRBV6', 'isotype': 'TR', 'chain_type': 'B'}],
        # allele name shorter than 3 chars: no isotype/chain type
        ['TR', {'allele_name': 'TR'}],
        [None, {}],
        ['', {}],
    )
    @unpack
    def test_parse_imgt_allele(self, input, expect):
        assert ParseBlastXml.parse_imgt_allele(input) == expect

